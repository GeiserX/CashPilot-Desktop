// Command i18nnsis writes build/windows/installer/i18n.nsh, the Windows
// installer's languages and its own strings, from the app's locale files.
//
// NSIS cannot read JSON, so the installer's text lives with the app's, under
// the installer.* keys of frontend/src/locales/<code>.json, and this command
// turns them into LangString lines. The installer then opens in the Windows
// display language when NSIS has that language (Filipino has no NSIS language
// and gets English). A key a locale lacks gets the English text, as in the app.
// A test fails when the committed file differs from what this writes.
//
//	go run ./cmd/i18nnsis          # rewrite the file
//	go run ./cmd/i18nnsis -check   # exit 1 when it is out of date
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// nsisLanguages maps our locale codes to NSIS language file names, in the order
// the installer lists them. English goes first: it is the fallback.
var nsisLanguages = []struct{ code, nsis string }{
	{"en", "English"}, {"es", "Spanish"}, {"pt-BR", "PortugueseBR"}, {"fr", "French"},
	{"de", "German"}, {"it", "Italian"}, {"nl", "Dutch"}, {"pl", "Polish"},
	{"ru", "Russian"}, {"uk", "Ukrainian"}, {"tr", "Turkish"}, {"ar", "Arabic"},
	{"hi", "Hindi"}, {"id", "Indonesian"}, {"vi", "Vietnamese"}, {"th", "Thai"},
	{"zh-Hans", "SimpChinese"}, {"ja", "Japanese"}, {"ko", "Korean"},
}

// args maps a message argument to the NSIS variable that fills it.
var args = map[string]string{"{dir}": "$INSTDIR", "{result}": "$0"}

const prefix = "installer."

func main() {
	locales := flag.String("locales", filepath.Join("frontend", "src", "locales"), "folder of <code>.json locale files")
	out := flag.String("out", filepath.Join("build", "windows", "installer", "i18n.nsh"), "file to write")
	check := flag.Bool("check", false, "exit 1 when the file is out of date instead of writing it")
	flag.Parse()

	want, err := generate(*locales)
	if err != nil {
		fmt.Fprintf(os.Stderr, "i18nnsis: %v\n", err)
		os.Exit(2)
	}
	if *check {
		have, _ := os.ReadFile(*out)
		if !bytes.Equal(have, want) {
			fmt.Fprintf(os.Stderr, "i18nnsis: %s is out of date; run go run ./cmd/i18nnsis\n", *out)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(*out, want, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "i18nnsis: %v\n", err)
		os.Exit(2)
	}
}

func read(dir, code string) (map[string]string, error) {
	raw, err := os.ReadFile(filepath.Join(dir, code+".json"))
	if err != nil {
		return nil, err
	}
	var m map[string]string
	if err := json.Unmarshal(raw, &m); err != nil {
		return nil, fmt.Errorf("%s.json: %w", code, err)
	}
	return m, nil
}

func generate(dir string) ([]byte, error) {
	en, err := read(dir, "en")
	if err != nil {
		return nil, err
	}
	var keys []string
	for k := range en {
		if strings.HasPrefix(k, prefix) {
			keys = append(keys, k)
		}
	}
	sort.Strings(keys)
	if len(keys) == 0 {
		return nil, fmt.Errorf("en.json has no %s keys", prefix)
	}

	var b bytes.Buffer
	b.WriteString("\uFEFF") // NSIS reads a file as UTF-8 only with a BOM
	b.WriteString("# Generated by `go run ./cmd/i18nnsis` from frontend/src/locales. Do not edit.\n\n")
	for _, l := range nsisLanguages {
		fmt.Fprintf(&b, "!insertmacro MUI_LANGUAGE \"%s\"\n", l.nsis)
	}
	for _, k := range keys {
		b.WriteString("\n")
		name := langName(k)
		for _, l := range nsisLanguages {
			msgs := en
			if l.code != "en" {
				if m, err := read(dir, l.code); err == nil {
					msgs = m
				}
			}
			msg := msgs[k]
			if msg == "" {
				msg = en[k]
			}
			value, err := nsisString(msg)
			if err != nil {
				return nil, fmt.Errorf("%s in %s: %w", k, l.code, err)
			}
			fmt.Fprintf(&b, "LangString %s ${LANG_%s} \"%s\"\n", name, strings.ToUpper(l.nsis), value)
		}
	}
	return b.Bytes(), nil
}

// langName turns installer.options.deleteData into OPTIONS_DELETEDATA.
func langName(key string) string {
	return strings.ToUpper(strings.ReplaceAll(strings.TrimPrefix(key, prefix), ".", "_"))
}

// nsisString escapes a message for a quoted NSIS string and puts the NSIS
// variables in for its arguments.
func nsisString(msg string) (string, error) {
	s := strings.NewReplacer("$", "$$", `"`, `$\"`, "\n", "$\\n", "\r", "", "\t", "$\\t").Replace(msg)
	for arg, variable := range args {
		s = strings.ReplaceAll(s, arg, variable)
	}
	if strings.ContainsAny(s, "{}") {
		return "", fmt.Errorf("an argument the installer cannot fill: %q", msg)
	}
	return s, nil
}
